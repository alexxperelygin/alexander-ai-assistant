// Правило входа, прошедшее предварительно зарегистрированную проверку.
//
// Зачем этот файл вообще появился. Бумажный портфель с самого начала входил по
// конвейеру скоринга (статус READY). Про этот конвейер к 17 августа известно
// ровно одно: backtest даёт NO EDGE (−5.7% на 24ч, −7.1% на 6ч), и живой
// портфель теряет деньги ровно так, как backtest и предсказывает — 3 прибыльные
// сделки из 17, минус $119.
//
// Одновременно проверка из `docs/PREREGISTRATION.md` прошла все пять критериев
// на 267 сделках после заморозки. Но прошла она НА ИСТОРИИ СНАПШОТОВ: это
// пересчёт по записанным наблюдениям, а не торговля. Живой проверки правило не
// получало ни разу.
//
// То есть система тратила единственный имеющийся живой стенд на стратегию, про
// которую уже известно, что она не работает, и не давала стенда той, которая
// проверку прошла. Этот модуль исправляет именно это.
//
// ВАЖНО: прохождение проверки НЕ означает, что стратегия прибыльна. Медиана
// сделки −1.3%, три четверти сделок убыточны, весь плюс держится на пяти
// сделках из 267, а фильтр исполнимости выхода выбрасывал 146 сделок из 267.
// Живой прогон нужен как раз потому, что пересчёт по истории всего этого не
// проверяет. Реальными деньгами система не торгует ни при каком исходе.

/** Каким правилом открыта позиция. Хранится в Position.entryRule. */
export type EntryRule = "ready-pipeline" | "validated-liquidity";

/**
 * Замороженные параметры входа. Числа взяты из `docs/PREREGISTRATION.md` и
 * менять их нельзя: правило проверялось именно в этом виде, и любая правка
 * превращает живой прогон в проверку чего-то другого.
 */
export const VALIDATED_ENTRY = {
  /** Ликвидность СТРОГО больше этого значения на момент наблюдения. */
  minLiquidityUsd: 50_000,
  /** Размер позиции, как в проверке. */
  positionSizeUsd: 50,
  /**
   * Потолок одновременно открытых позиций этого трека.
   *
   * Числа в проверке потолка не имеют: там входы берутся все подряд, около 26
   * в сутки, и при удержании до 3 суток одновременно «открыто» бывает под 80
   * позиций. Здесь потолок есть, и причина у него не финансовая — бумажные
   * деньги ничем не рискуют, — а инфраструктурная: монитор раз в 30 секунд
   * делает по одному запросу цены на каждую открытую позицию, а VPS общий с
   * другими приложениями владельца. 25 позиций — это 50 запросов в минуту
   * поверх сканера, что укладывается в тротлинг провайдера с запасом.
   *
   * Расплата за потолок названа честно в `docs/PREREGISTRATION.md`: входы
   * берутся не все подряд, а те, что подвернулись при свободном слоте.
   */
  maxOpenPositions: 25,
} as const;

/**
 * Начало живого прогона. Сделки этого трека раньше этого момента невозможны,
 * и по этой дате их отделяют от прежних при разборе результата.
 */
export const VALIDATED_LIVE_FROM = new Date("2026-08-17T00:00:00Z");

export interface EntryObservation {
  liquidityUsd?: number | null;
  priceUsd?: number | null;
  priceChange1h?: number | null;
  priceChange24h?: number | null;
}

export type EntryVerdict =
  | { fires: true }
  | { fires: false; reason: string };

/**
 * Срабатывает ли замороженное правило входа на этом наблюдении.
 *
 * Здесь намеренно НЕТ проверок риска, скоринга, возраста и социальных
 * сигналов. Правило проверялось без них; добавить сюда хоть один
 * дополнительный фильтр — значит проверять живьём не то правило, которое
 * прошло проверку, и обнулить весь смысл прогона.
 */
export function validatedEntryFires(obs: EntryObservation): EntryVerdict {
  if (obs.priceUsd == null || !(obs.priceUsd > 0)) return { fires: false, reason: "нет цены" };
  const liq = obs.liquidityUsd ?? 0;
  if (!(liq > VALIDATED_ENTRY.minLiquidityUsd))
    return { fires: false, reason: `ликвидность $${Math.round(liq).toLocaleString("ru")} ≤ $${VALIDATED_ENTRY.minLiquidityUsd.toLocaleString("ru")}` };
  // Артефакт листинга: у пары, у которой в источнике меньше часа истории,
  // Δ1ч в точности равна Δ24ч. Цена входа в такой момент наименее надёжна, а
  // именно такие наблюдения и создавали основную часть положительного хвоста
  // в первых версиях исследования.
  if (obs.priceChange1h != null && obs.priceChange24h != null &&
      obs.priceChange1h === obs.priceChange24h)
    return { fires: false, reason: "артефакт листинга: Δ1ч = Δ24ч" };
  return { fires: true };
}
