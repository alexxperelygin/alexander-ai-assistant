// Замороженные правила выхода. Одно место на весь проект: по ним торгует
// бумажный портфель и по ним же считается исследование. Если бы константы
// жили в двух файлах, отчёт рано или поздно начал бы проверять не ту
// стратегию, которой торгует система, и мы бы этого не заметили.
//
// Даты и обоснование — docs/PREREGISTRATION.md. Менять эти числа до
// 15 августа нельзя: любая правка обнуляет накопленную out-of-sample
// проверку, потому что превращает правило обратно в подобранное под
// увиденные данные.

export interface FrozenExitPolicy {
  /** Жёсткий стоп от цены входа, доля: 0.2 = −20%. */
  stopPct: number;
  /** Трейлинг-стоп от достигнутого максимума, доля. */
  trailPct: number;
  /** Аварийный выход, если ликвидность упала ниже этой доли от входной. */
  liquidityFloorRatio: number;
  /** Предельное время удержания, минуты. */
  maxHoldMin: number;
}

export const FROZEN_EXIT: FrozenExitPolicy = {
  stopPct: 0.2,
  trailPct: 0.3,
  // Правило по ликвидности добавлено ради безопасности, а не потому, что
  // улучшало цифру: без него позиция в ругпулле досиживает до стопа, когда
  // продать уже некому. В исследовании оно моделируется явно, чтобы отчёт
  // и живой портфель считали одно и то же.
  liquidityFloorRatio: 0.6,
  maxHoldMin: 3 * 24 * 60,
};

/** Момент заморозки: сделки раньше него — подгонка, позже — проверка. */
export const FREEZE_AT = new Date("2026-08-08T17:00:00Z");
