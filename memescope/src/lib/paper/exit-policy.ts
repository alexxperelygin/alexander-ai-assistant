// Венчурный формат. Отдельный тест, отдельная заморозка, отдельные критерии.
//
// Основание: из всего исследования out-of-sample воспроизвелось ровно одно
// свойство — ЧАСТОТА хвостов. Доля сделок с ростом больше +100% составила
// 7.22% на исторических данных и 6.82% на данных после первой заморозки,
// против 2.57% у «купить любой токен». При этом тело распределения (всё,
// кроме выигрышей больше 10x) после заморозки даёт +0.2% — то есть обычные
// сделки не зарабатывают, но и не проедают депозит.
//
// Это и есть условие, при котором венчурный формат имеет смысл: за право
// держать лотерейный билет мы не доплачиваем. Проверять такой формат прежним
// критерием «среднее без лучшей сделки > 0» нельзя — ему по построению не
// удовлетворяет ни один венчурный портфель, включая прибыльные.

/** Правила выхода венчурного теста. Отличие одно: трейлинга нет. */
export const VENTURE_EXIT: FrozenExitPolicy = {
  // Стоп остаётся: именно он удерживает тело распределения около нуля.
  // Без него обычные сделки начнут проедать депозит, и хвост перестанет
  // окупаться — вся конструкция держится на том, что тело не убыточно.
  stopPct: 0.2,
  // Трейлинг убран, и это главное изменение. Он закрывает позицию при откате
  // на 30% от максимума, то есть обрубает ровно тот рост в десятки раз, ради
  // которого венчурный формат и существует.
  trailPct: 0,
  liquidityFloorRatio: 0.6,
  // Срок удержания оставлен прежним намеренно. Больше — значит дольше ждать
  // измеримого исхода: при недельном окне данных семидневное удержание
  // сделало бы свежие сделки неизмеримыми, и проверка встала бы.
  maxHoldMin: 3 * 24 * 60,
};

/** Начало венчурной проверки. Сделки раньше него в неё не входят. */
export const VENTURE_FREEZE_AT = new Date("2026-08-10T12:00:00Z");
